// Days 1–95 ran on the original 92-song list, so 93–95 wrapped back to its
// start (Toxic, Billie Jean, Dancing Queen). Those days keep that mapping so
// past days and their leaderboards stay valid; from day 96 the rotation picks
// up with the songs appended after the original 92. Appending is safe until
// the rotation wraps again (day 96 + SONGS.length - 92); after that, start a
// new epoch like this one rather than letting the modulo shift past days.
const ORIGINAL_COUNT = 92;
const EXPANDED_FROM_DAY = 96;

const mod = (n: number, m: number) => ((n % m) + m) % m;

export function songForDay(day: number): Song {
  if (day < EXPANDED_FROM_DAY) return SONGS[mod(day - 1, ORIGINAL_COUNT)];
  return SONGS[mod(day - EXPANDED_FROM_DAY + ORIGINAL_COUNT, SONGS.length)];
}
